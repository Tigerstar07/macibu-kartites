import type { Card, CategoryId, Deck, DeckIcon } from '../types';

type CardRow = [question: string, answer: string, wrong: string[], explanation?: string];

interface SubjectDeckInput {
  id: string;
  title: string;
  description: string;
  category: CategoryId;
  tags: string[];
  icon: DeckIcon;
  hue: number;
  rankIndex: number;
  prefix: string;
  cards: CardRow[];
}

const CREATED_AT = new Date(2026, 8, 1).getTime();

function subjectDeck(input: SubjectDeckInput): Deck {
  const cards: Card[] = input.cards.map(([question, answer, wrong, explanation], index) => ({
    id: `${input.prefix}${index + 1}`,
    question,
    answer,
    wrong,
    explanation,
  }));

  return {
    id: input.id,
    title: input.title,
    description: input.description,
    category: input.category,
    language: 'lv',
    tags: input.tags,
    icon: input.icon,
    hue: input.hue,
    rankIndex: input.rankIndex,
    reversible: false,
    ask: 'Izvēlies pareizo atbildi!',
    cards,
    author: 'Mācību kartītes',
    builtin: true,
    isPublic: true,
    createdAt: CREATED_AT,
    updatedAt: CREATED_AT,
  };
}

